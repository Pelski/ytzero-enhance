export function uiLanguage() {
  let language = (globalThis as any).navigator?.language || "en";
  try { language = ((globalThis as any).browser ?? (globalThis as any).chrome)?.i18n?.getUILanguage?.() || language; }
  catch {}
  return /^pl\b/i.test(language) ? "pl" : /^de\b/i.test(language) ? "de" : "en";
}

export function t(key: string): string {
  try {
    const localized = ((globalThis as any).browser ?? (globalThis as any).chrome)?.i18n?.getMessage?.(key);
    return localized || EN[key] || key;
  } catch { return EN[key] || key; }
}

export function localizeDocument(root: ParentNode = document) {
  if (typeof document !== "undefined") document.documentElement.lang = uiLanguage();
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n!); });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((element) => { element.setAttribute("aria-label", t(element.dataset.i18nAria!)); });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => { element.title = t(element.dataset.i18nTitle!); });
}
